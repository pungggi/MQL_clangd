const assert = require('assert');

const { _test } = require('../src/noisyDiagnostic');
const { extractDiagnosticCode, isClangdDiagnostic, pickDiagnosticAt, buildReportText, insertSuppression } = _test;

/** A range stub: a diagnostic covers a line range [startLine, endLine] at columns 0..999. */
function rangeStub(startLine, endLine = startLine) {
    return {
        start: { line: startLine, character: 0 },
        end: { line: endLine, character: 999 },
        contains: (position) => position.line >= startLine && position.line <= endLine,
        intersects: () => true,
        intersection: () => undefined,
    };
}

function diagnostic({ source = 'clang', code = 'unknown_type', message = 'unknown type name \'CFoo\'', line = 4, severity = 0 }) {
    return { source, code, message, severity, range: rangeStub(line) };
}

// A realistic .clangd as generated by createProperties.js.
const GENERATED_CLANGD = [
    '# MQL Clangd Configuration',
    '# Auto-generated by MQL Clangd extension',
    '',
    'Diagnostics:',
    '  Suppress:',
    '    - pp_file_not_found',
    '    - lexing_error',
    '',
    '  ClangTidy:',
    '    Remove:',
    '      - modernize-*',
    '',
    'CompileFlags:',
    '  Add:',
    '    - -Wno-everything',
    '',
].join('\n');

suite('noisyDiagnostic — extractDiagnosticCode', () => {
    test('returns a string code as-is', () => {
        assert.strictEqual(extractDiagnosticCode({ code: 'unknown_type' }), 'unknown_type');
    });

    test('unwraps a { value } code object', () => {
        assert.strictEqual(extractDiagnosticCode({ code: { value: 'MQL199' } }), 'MQL199');
    });

    test('trims whitespace', () => {
        assert.strictEqual(extractDiagnosticCode({ code: '  -Wunused-result ' }), '-Wunused-result');
    });

    test('returns empty string for missing, null or numeric codes', () => {
        assert.strictEqual(extractDiagnosticCode({}), '');
        assert.strictEqual(extractDiagnosticCode({ code: null }), '');
        assert.strictEqual(extractDiagnosticCode({ code: 123 }), '');
        assert.strictEqual(extractDiagnosticCode(undefined), '');
    });
});

suite('noisyDiagnostic — isClangdDiagnostic', () => {
    test('accepts the sources vscode-clangd publishes', () => {
        assert.strictEqual(isClangdDiagnostic({ source: 'clang' }), true);
        assert.strictEqual(isClangdDiagnostic({ source: 'clangd' }), true);
        assert.strictEqual(isClangdDiagnostic({ source: 'Clang-Tidy' }), true);
    });

    test('rejects MetaEditor and extension sources', () => {
        assert.strictEqual(isClangdDiagnostic({ source: 'mql' }), false);
        assert.strictEqual(isClangdDiagnostic({ source: 'mql-clangd-unresolved' }), false);
        assert.strictEqual(isClangdDiagnostic({}), false);
        assert.strictEqual(isClangdDiagnostic(undefined), false);
    });
});

suite('noisyDiagnostic — pickDiagnosticAt', () => {
    test('returns the diagnostic covering the cursor', () => {
        const d = diagnostic({ line: 3 });
        assert.strictEqual(pickDiagnosticAt([d], { line: 3, character: 7 }), d);
    });

    test('returns undefined when nothing covers the cursor', () => {
        assert.strictEqual(pickDiagnosticAt([diagnostic({ line: 3 })], { line: 9, character: 0 }), undefined);
        assert.strictEqual(pickDiagnosticAt([], { line: 0, character: 0 }), undefined);
        assert.strictEqual(pickDiagnosticAt(undefined, { line: 0, character: 0 }), undefined);
    });

    test('prefers the clangd diagnostic over a MetaEditor one on the same line', () => {
        const metaEditor = diagnostic({ source: 'mql', code: { value: 'MQL199' } });
        const clangd = diagnostic({ source: 'clang' });
        assert.strictEqual(pickDiagnosticAt([metaEditor, clangd], { line: 4, character: 1 }), clangd);
    });

    test('falls back to a non-clangd diagnostic when it is the only one', () => {
        const metaEditor = diagnostic({ source: 'mql', code: { value: 'MQL199' } });
        assert.strictEqual(pickDiagnosticAt([metaEditor], { line: 4, character: 1 }), metaEditor);
    });

    test('ignores diagnostics whose range is unusable', () => {
        const broken = { source: 'clang', message: 'x', range: { start: { line: 0, character: 0 }, contains: () => { throw new Error('boom'); } } };
        assert.strictEqual(pickDiagnosticAt([broken], { line: 0, character: 0 }), undefined);
        assert.strictEqual(pickDiagnosticAt([{ source: 'clang' }], { line: 0, character: 0 }), undefined);
    });
});

suite('noisyDiagnostic — insertSuppression', () => {
    test('appends to an existing Suppress list and leaves the rest untouched', () => {
        const result = insertSuppression(GENERATED_CLANGD, 'unknown_type');
        assert.strictEqual(result.added, true);
        assert.strictEqual(result.alreadyPresent, false);
        const lines = result.text.split('\n');
        const suppressIdx = lines.indexOf('  Suppress:');
        assert.deepStrictEqual(lines.slice(suppressIdx + 1, suppressIdx + 4),
            ['    - pp_file_not_found', '    - lexing_error', '    - unknown_type']);
        // Everything after the list is byte-identical.
        assert.ok(result.text.includes('  ClangTidy:\n    Remove:\n      - modernize-*'));
        assert.ok(result.text.includes('CompileFlags:\n  Add:\n    - -Wno-everything'));
        assert.ok(result.text.startsWith('# MQL Clangd Configuration'));
    });

    test('is idempotent', () => {
        const once = insertSuppression(GENERATED_CLANGD, 'unknown_type');
        const twice = insertSuppression(once.text, 'unknown_type');
        assert.strictEqual(twice.added, false);
        assert.strictEqual(twice.alreadyPresent, true);
        assert.strictEqual(twice.text, once.text);
    });

    test('detects an existing entry that carries a trailing comment', () => {
        const content = [
            'Diagnostics:',
            '  Suppress:',
            '    - lexing_error  # noisy in MQL',
            '',
        ].join('\n');
        const result = insertSuppression(content, 'lexing_error');
        assert.strictEqual(result.alreadyPresent, true);
        assert.strictEqual(result.text, content);
    });

    test('detects an existing quoted entry', () => {
        const result = insertSuppression('Diagnostics:\n  Suppress:\n    - "lexing_error"\n', 'lexing_error');
        assert.strictEqual(result.alreadyPresent, true);
    });

    test('creates the whole block for an empty or missing file', () => {
        const result = insertSuppression('', 'unknown_type');
        assert.strictEqual(result.added, true);
        assert.strictEqual(result.text, 'Diagnostics:\n  Suppress:\n    - unknown_type\n');

        const fromUndefined = insertSuppression(undefined, 'unknown_type');
        assert.strictEqual(fromUndefined.text, 'Diagnostics:\n  Suppress:\n    - unknown_type\n');
    });

    test('keeps existing content when adding a missing Diagnostics block', () => {
        const content = 'CompileFlags:\n  Add:\n    - -xc++\n';
        const result = insertSuppression(content, 'pp_file_not_found');
        assert.strictEqual(result.added, true);
        assert.ok(result.text.startsWith('CompileFlags:\n  Add:\n    - -xc++\n'));
        assert.ok(result.text.includes('Diagnostics:\n  Suppress:\n    - pp_file_not_found'));
    });

    test('adds Suppress to a Diagnostics block that has none', () => {
        const content = 'Diagnostics:\n  ClangTidy:\n    Remove:\n      - modernize-*\n';
        const result = insertSuppression(content, 'unknown_type');
        assert.strictEqual(
            result.text,
            'Diagnostics:\n  Suppress:\n    - unknown_type\n  ClangTidy:\n    Remove:\n      - modernize-*\n',
        );
    });

    test('rewrites a flow-style list into a block list', () => {
        const content = 'Diagnostics:\n  Suppress: [pp_file_not_found, lexing_error]\n';
        const result = insertSuppression(content, 'unknown_type');
        assert.strictEqual(result.added, true);
        assert.strictEqual(
            result.text,
            'Diagnostics:\n  Suppress:\n    - pp_file_not_found\n    - lexing_error\n    - unknown_type\n',
        );
    });

    test('detects a flag inside a flow-style list', () => {
        const content = 'Diagnostics:\n  Suppress: [pp_file_not_found, lexing_error]\n';
        assert.strictEqual(insertSuppression(content, 'lexing_error').alreadyPresent, true);
    });

    test('tolerates blank lines inside the list', () => {
        const content = 'Diagnostics:\n  Suppress:\n    - a\n\n    - b\n\n  ClangTidy:\n    Remove:\n      - x\n';
        const result = insertSuppression(content, 'c');
        assert.strictEqual(result.added, true);
        assert.ok(result.text.includes('    - b\n    - c\n'));
        assert.ok(result.text.includes('  ClangTidy:\n    Remove:\n      - x'));
    });

    test('preserves CRLF line endings', () => {
        const content = 'Diagnostics:\r\n  Suppress:\r\n    - a\r\n';
        const result = insertSuppression(content, 'b');
        assert.strictEqual(result.text, 'Diagnostics:\r\n  Suppress:\r\n    - a\r\n    - b\r\n');
        assert.strictEqual(result.text.includes('\n\n'), false);
    });

    test('ignores an empty flag', () => {
        const result = insertSuppression(GENERATED_CLANGD, '   ');
        assert.strictEqual(result.added, false);
        assert.strictEqual(result.text, GENERATED_CLANGD);
    });
});

suite('noisyDiagnostic — buildReportText', () => {
    const doc = {
        fileName: 'C:\\MT5\\MQL5\\Experts\\MyEA.mq5',
        lineAt: (line) => ({ text: line === 4 ? '   int x = Unknown();' : '' }),
    };

    test('includes location, source, code, severity and message', () => {
        const text = buildReportText(diagnostic({ line: 4 }), doc, { extensionVersion: '1.1.63', vscodeVersion: '1.99.0' });
        assert.ok(text.includes('`MyEA.mq5` line 5, column 1'));
        assert.ok(text.includes('- Source: clang'));
        assert.ok(text.includes('- Code: unknown_type'));
        assert.ok(text.includes('- Severity: error'));
        assert.ok(text.includes("- Message: unknown type name 'CFoo'"));
        assert.ok(text.includes('- MQL Clangd: 1.1.63'));
        assert.ok(text.includes('- VS Code: 1.99.0'));
    });

    test('includes the offending source line as a snippet', () => {
        const text = buildReportText(diagnostic({ line: 4 }), doc);
        assert.ok(text.includes('```mql\nint x = Unknown();\n```'));
    });

    test('works without a document or metadata', () => {
        const text = buildReportText(diagnostic({ line: 0 }), undefined);
        assert.ok(text.includes('`unknown` line 1, column 1'));
        assert.strictEqual(text.includes('```mql'), false);
    });

    test('falls back for unknown severity and missing code', () => {
        const text = buildReportText({ range: rangeStub(0), severity: 99, message: 'x' }, undefined);
        assert.ok(text.includes('- Severity: unknown'));
        assert.ok(text.includes('- Code: (none)'));
        assert.ok(text.includes('- Source: (unknown)'));
    });
});
